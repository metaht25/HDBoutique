import { expect, test } from '@playwright/test'
import { mockBoutique } from '../fixtures/boutique'
test('employee creation includes credentials and direct municipality selection', async ({ page }) => {
  await mockBoutique(page); await page.goto('/employees'); await page.getByRole('button', { name: '+ Nuevo empleado' }).click()
  const dialog = page.getByRole('dialog', { name: 'Nuevo empleado' })
  await expect(dialog.getByLabel('Usuario de acceso')).toBeVisible(); await expect(dialog.getByLabel('Contraseña', { exact: true })).toHaveAttribute('type', 'password')
  await expect(dialog.getByLabel('Municipio', { exact: true })).toBeDisabled()
  await dialog.getByLabel('Departamento', { exact: true }).click(); await dialog.getByRole('listbox', { name: 'Departamento' }).getByRole('option').first().click()
  await expect(dialog.getByLabel('Municipio', { exact: true })).toBeEnabled()
  const phone = dialog.getByLabel('Teléfono', { exact: true })
  await phone.fill('80000000'); await expect(phone).toHaveValue('8000-0000')
  await phone.press('Home'); await phone.press('ArrowRight'); await phone.press('Delete')
  await expect(phone).toHaveValue('8000-000')
  await phone.press('7'); await expect(phone).toHaveValue('8700-0000')
  await phone.evaluate((input: HTMLInputElement) => input.setSelectionRange(5, 5))
  await phone.press('Backspace'); await expect(phone).toHaveValue('8700-000')
  await phone.fill('8000-0000'); await expect(phone).toHaveValue('8000-0000')
  await phone.fill(''); await phone.pressSequentially('abcd81234567')
  await expect(phone).toHaveValue('8123-4567')
  await dialog.getByLabel('Contraseña', { exact: true }).fill('abc123')
  await dialog.getByRole('button', { name: 'Mostrar contraseña', exact: true }).click()
  await expect(dialog.getByLabel('Contraseña', { exact: true })).toHaveAttribute('type', 'text')
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByRole('button', { name: '+ Nuevo empleado' }).click()
  await expect(page.getByLabel('Contraseña', { exact: true })).toHaveValue('')
})
test('assigned credentials permit business access without password replacement', async ({ page }) => {
  await mockBoutique(page, 'Cashier')
  await page.goto('/new-sale'); await expect(page.getByRole('heading', { level: 1, name: 'Nueva venta' })).toBeVisible()
  await expect(page.getByText('Turno de caja')).toHaveCount(0)
})
