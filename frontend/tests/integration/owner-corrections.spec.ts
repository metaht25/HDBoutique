import { expect, test } from '@playwright/test'
import { capture, selectAddress, signIn } from './helpers'

test('owner creates and edits an employee using a controlled job title', async ({ page }, info) => {
  await signIn(page); await page.goto('/employees')
  await page.getByRole('button', { name: '+ Nuevo empleado' }).click()
  const modal = page.getByRole('dialog', { name: 'Nuevo empleado' })
  await modal.getByLabel('Nombres', { exact: true }).fill('Empleado auditoría')
  await modal.getByLabel('Apellidos', { exact: true }).fill('Sintético')
  await modal.getByLabel('Teléfono', { exact: true }).fill('81234567')
  await expect(modal.getByLabel('Cargo', { exact: true })).toHaveAttribute('readonly', '')
  await modal.getByLabel('Usuario de acceso', { exact: true }).fill('audit-job-title')
  await modal.getByLabel('Contraseña', { exact: true }).fill('Synthetic-password-27!')
  await selectAddress(page)
  await capture(page, info, 'employee-cargo-desktop')
  await page.setViewportSize({ width: 390, height: 844 }); await capture(page, info, 'employee-cargo-mobile')
  await page.setViewportSize({ width: 1440, height: 1000 })
  const created = page.waitForResponse(res => res.url().endsWith('/api/v1/employees') && res.request().method() === 'POST')
  await modal.getByRole('button', { name: 'Guardar empleado' }).click()
  const response = await created; expect(response.status()).toBe(201)
  const employee = await response.json(); expect(employee.job_title).toBe('Vendedor'); expect(employee.phone_number).toBe('81234567')
  const row = page.getByRole('row').filter({ hasText: 'Empleado auditoría Sintético' })
  await row.getByRole('button', { name: 'Editar', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Editar empleado' })
  await expect(edit.getByLabel('Cargo', { exact: true })).toHaveValue('Vendedor')
  await expect(edit.getByLabel('Cargo', { exact: true })).toHaveAttribute('readonly', '')
  const updated = page.waitForResponse(res => res.url().endsWith('/api/v1/employees/' + employee.employee_id) && res.request().method() === 'PATCH')
  await edit.getByRole('button', { name: 'Guardar cambios' }).click()
  expect((await (await updated).json()).job_title).toBe('Vendedor')
  await expect(edit).toHaveCount(0)
})
