import { expect, test } from '@playwright/test'
import { command, origin, signIn } from './helpers'

test('sales detail retains full mixed refund, actual merchandise returns and idempotent annulment', async ({ page }) => {
  await signIn(page)
  const products = await (await page.request.get('/api/v1/products?limit=100')).json()
  const first = products.find((row: { name: string }) => row.name === 'Synthetic 1'), second = products.find((row: { name: string }) => row.name === 'Synthetic 2')
  const created = await command(page, 'sales', { customer_kind: 'general', items: [{ product_id: first.product_id, quantity: 2 }, { product_id: second.product_id, quantity: 1 }], payment: { method: 'mixed', received_amount: '1000.00', transfer_amount: '20.00', transfer_confirmed: true } }, 'POST', 'sales-ui-mixed-refund')
  expect(created.status()).toBe(201); const sale = await created.json()
  await page.goto('/sales')
  const row = page.getByRole('row').filter({ has: page.getByText(`V-${String(sale.sale_id).padStart(5, '0')}`, { exact: true }) })
  await row.getByRole('button', { name: 'Ver', exact: true }).click()
  const detail = page.getByRole('dialog', { name: `Venta V-${String(sale.sale_id).padStart(5, '0')}` })
  await expect(detail.getByRole('heading', { name: 'Desglose de importes' })).toBeVisible()
  await detail.getByRole('button', { name: 'Anular venta', exact: true }).click()
  await detail.getByLabel('Motivo de anulación', { exact: true }).fill('Anulación sintética con devolución física parcial')
  await detail.getByLabel(`Cantidad devuelta de producto #${first.product_id} (vendidas 2)`, { exact: true }).fill('1')
  await detail.getByLabel(`Cantidad devuelta de producto #${second.product_id} (vendidas 1)`, { exact: true }).fill('0')
  await detail.getByLabel('Referencia del reintegro por transferencia').fill('SYNTHETIC-REFUND-UI')
  await detail.getByLabel('Confirmo el reintegro completo al cliente y las cantidades devueltas').check()
  const voided = page.waitForResponse(response => response.url().endsWith(`/sales/${sale.sale_id}/void`) && response.request().method() === 'POST')
  await detail.getByRole('button', { name: 'Confirmar anulación total', exact: true }).click()
  const response = await voided; expect(response.status()).toBe(201)
  const result = await response.json()
  expect(result.amount).toBe(sale.total)
  expect(result.cash_amount).toBe(sale.payment.cash_amount); expect(result.transfer_amount).toBe(sale.payment.transfer_amount)
  await expect(detail.getByText('Anulada', { exact: true })).toBeVisible()
  await expect(detail.getByRole('button', { name: 'Anular venta', exact: true })).toHaveCount(0)
  const headers = await response.request().allHeaders(), csrf = (await (await page.request.get('/api/v1/auth/csrf')).json()).csrf_token
  const repeated = await page.request.post(`/api/v1/sales/${sale.sale_id}/void`, { data: response.request().postDataJSON(), headers: { Origin: origin, 'X-CSRF-Token': csrf, 'Idempotency-Key': headers['idempotency-key']!, 'X-Idempotency-Actor': headers['x-idempotency-actor']! } })
  expect(repeated.status()).toBe(201); expect(await repeated.json()).toEqual(result)
  expect((await (await page.request.get('/api/v1/products/' + first.product_id)).json()).legacy_stock).toBe(first.legacy_stock - 1)
  expect((await (await page.request.get('/api/v1/products/' + second.product_id)).json()).legacy_stock).toBe(second.legacy_stock - 1)
  const preserved = await (await page.request.get('/api/v1/sales/' + sale.sale_id)).json()
  expect(preserved.items).toEqual(sale.items); expect(preserved.payment).toEqual(sale.payment)
  const ledger = await (await page.request.get('/api/v1/reports/sales-ledger?q=' + sale.sale_id)).json()
  expect(ledger.summary.total_amount).toBe('0.00'); expect(ledger.summary.units).toBe(0)
})
