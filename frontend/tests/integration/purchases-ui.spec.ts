import { expect, test } from '@playwright/test'
import { origin, signIn } from './helpers'

test('pending purchase leaves stock unchanged and complete receipt is applied only once', async ({ page }) => {
  await signIn(page)
  const products = await (await page.request.get('/api/v1/products?limit=20')).json()
  const suppliers = await (await page.request.get('/api/v1/suppliers?limit=20')).json()
  const product = products.find((row: { name: string }) => row.name === 'Synthetic 1')
  const supplier = suppliers.find((row: { company_name: string }) => row.company_name === 'Synthetic 1')
  expect(product).toBeTruthy(); expect(supplier).toBeTruthy()
  const before = product.legacy_stock
  await page.goto('/purchases'); await page.getByRole('button', { name: '+ Nueva compra' }).click()
  const form = page.getByRole('dialog', { name: 'Nueva compra' })
  await form.getByRole('combobox', { name: 'Proveedor' }).fill(supplier.company_name)
  await form.getByRole('option', { name: supplier.company_name, exact: true }).click()
  await form.getByRole('combobox', { name: 'Producto' }).fill(product.name)
  await form.getByRole('option', { name: product.name, exact: true }).click()
  await form.getByLabel('Cantidad', { exact: true }).fill('2')
  await form.getByRole('button', { name: 'Agregar producto' }).click()
  const created = page.waitForResponse(res => res.url().endsWith('/api/v1/purchases') && res.request().method() === 'POST')
  await form.getByRole('button', { name: 'Guardar compra pendiente' }).click()
  const response = await created; expect(response.status()).toBe(201)
  const purchase = await response.json()
  expect(purchase.status).toBe('registered')
  expect((await (await page.request.get('/api/v1/products/' + product.product_id)).json()).legacy_stock).toBe(before)
  const row = page.getByRole('row').filter({ has: page.getByText('#' + purchase.purchase_id, { exact: true }) })
  await row.getByRole('button', { name: 'Ver / recibir' }).click()
  await page.getByRole('dialog', { name: 'Compra #' + purchase.purchase_id, exact: true }).getByRole('button', { name: 'Marcar como recibida' }).click()
  const confirmed = page.waitForResponse(res => res.url().endsWith(`/purchases/${purchase.purchase_id}/receive`) && res.request().method() === 'POST')
  await page.getByRole('dialog', { name: 'Confirmar recepción', exact: true }).getByRole('button', { name: 'Confirmar recepción', exact: true }).click()
  const receipt = await confirmed; expect(receipt.status()).toBe(200)
  const original = await receipt.json(), headers = await receipt.request().allHeaders()
  expect(original.status).toBe('received')
  const csrf = (await (await page.request.get('/api/v1/auth/csrf')).json()).csrf_token
  const repeated = await page.request.post(`/api/v1/purchases/${purchase.purchase_id}/receive`, { data: {}, headers: { Origin: origin, 'X-CSRF-Token': csrf, 'Idempotency-Key': headers['idempotency-key']!, 'X-Idempotency-Actor': headers['x-idempotency-actor']! } })
  expect(repeated.status()).toBe(200); expect(await repeated.json()).toEqual(original)
  expect((await (await page.request.get('/api/v1/products/' + product.product_id)).json()).legacy_stock).toBe(before + 2)
  const movements = await (await page.request.get(`/api/v1/inventory/movements?purchase_id=${purchase.purchase_id}`)).json()
  expect(movements.filter((entry: { movement_type: string }) => entry.movement_type === 'purchase_receipt')).toHaveLength(1)
})
