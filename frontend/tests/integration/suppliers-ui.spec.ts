import { expect, test } from '@playwright/test'
import { signIn } from './helpers'

test('supplier registered from purchase persists after the unsaved purchase is closed', async ({ page }) => {
  await signIn(page)
  const before = await (await page.request.get('/api/v1/purchases?limit=100')).json()
  await page.goto('/purchases'); await page.getByRole('button', { name: '+ Nueva compra' }).click()
  await page.getByRole('button', { name: '+ Registrar proveedor' }).click()
  const form = page.getByRole('dialog', { name: 'Nuevo proveedor' })
  await form.getByLabel('Empresa', { exact: true }).fill('UI Proveedor persistente')
  await form.getByLabel('Nombres del contacto').fill('Contacto')
  await form.getByLabel('Apellidos del contacto').fill('Sintético')
  await form.getByLabel('Teléfono', { exact: true }).fill('81234001')
  await form.getByLabel('Correo', { exact: true }).fill('ui@example.invalid')
  await form.getByLabel('Dirección exacta (opcional)').fill('Dirección de ensayo aislado')
  const saved = page.waitForResponse(res => res.url().endsWith('/purchases/suppliers') && res.request().method() === 'POST')
  await form.getByRole('button', { name: 'Guardar proveedor' }).click()
  const response = await saved; expect(response.status()).toBe(201)
  const supplier = await response.json()
  await expect(form).toHaveCount(0)
  const purchase = page.getByRole('dialog', { name: 'Nueva compra' })
  await expect(purchase.getByRole('combobox', { name: 'Proveedor' })).toHaveValue(supplier.company_name)
  await purchase.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await page.goto('/suppliers')
  await page.getByLabel('Buscar', { exact: true }).fill(supplier.company_name)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: supplier.company_name })
  await expect(row.getByRole('button', { name: 'Ver detalle' })).toBeVisible()
  const persisted = await (await page.request.get('/api/v1/suppliers/' + supplier.supplier_id)).json()
  expect(persisted.company_name).toBe(supplier.company_name); expect(persisted.address_line).toBe('Dirección de ensayo aislado')
  const after = await (await page.request.get('/api/v1/purchases?limit=100')).json()
  expect(after).toEqual(before)
})
