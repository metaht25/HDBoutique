import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const password = 'Synthetic-password-27!'
async function signIn(page: Page, username: string, accountPassword = password) {
  await page.goto('/settings')
  await page.getByLabel('Usuario', { exact: true }).fill(username)
  await page.getByLabel('Contraseña', { exact: true }).fill(accountPassword)
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible()
}
async function saveReference(page: Page, section: string, text: string): Promise<number> {
  await page.goto(`/settings?section=${section}`)
  await page.getByRole('textbox').fill(text)
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  const saved = page.getByText(/Registro #\d+ guardado correctamente/)
  await expect(saved).toBeVisible()
  return Number((await saved.textContent())?.match(/#(\d+)/)?.[1])
}

test('initial setup prepares references, account, purchase, cash and first sale through the UI', async ({ page }, testInfo) => {
  test.setTimeout(120000)
  await signIn(page, 'purchasing-administrator')
  const departmentId = await saveReference(page, 'departments', 'Setup department')
  await page.goto('/settings?section=addresses')
  await page.getByLabel('Departamento', { exact: true }).selectOption(String(departmentId))
  await page.getByLabel('Detalle de dirección').fill('Setup address')
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  const addressNotice = page.getByText(/Registro #\d+ guardado correctamente/)
  await expect(addressNotice).toBeVisible()
  const addressId = Number((await addressNotice.textContent())?.match(/#(\d+)/)?.[1])
  const categoryId = await saveReference(page, 'categories', 'Setup category')
  const sizeId = await saveReference(page, 'sizes', 'Setup size')
  const typeId = await saveReference(page, 'customer-types', 'Setup type')

  await page.goto('/employees')
  await page.getByLabel('Nombres', { exact: true }).fill('Setup employee')
  await page.getByLabel('Apellidos', { exact: true }).fill('Synthetic')
  await page.getByLabel('Teléfono', { exact: true }).fill('0012345678')
  await page.getByLabel('Dirección existente').selectOption(String(addressId))
  await page.getByRole('button', { name: 'Guardar empleado' }).click()
  await expect(page.getByText(/Empleado #\d+ guardado correctamente/)).toBeVisible()
  await page.goto('/settings?section=accounts')
  await page.getByLabel('Usuario', { exact: true }).fill('setup-cashier')
  await page.getByLabel('Empleado vinculado').selectOption({ label: await page.getByLabel('Empleado vinculado').getByRole('option').filter({ hasText: 'Setup employee Synthetic' }).textContent() ?? '' })
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  await page.getByLabel('Repetir contraseña', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click()
  await expect(page.getByText('Cuenta setup-cashier guardada correctamente.')).toBeVisible()
  await page.getByRole('button', { name: 'Editar cuenta setup-cashier', exact: true }).click()
  await page.getByLabel('Nueva contraseña (opcional)').fill('Synthetic-password-28!')
  await page.getByLabel('Repetir contraseña', { exact: true }).fill('Synthetic-password-28!')
  await page.getByRole('button', { name: 'Actualizar cuenta', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Crear cuenta', exact: true })).toBeVisible()

  await page.goto('/products')
  await page.getByLabel('Nombre', { exact: true }).fill('Setup product')
  await page.getByLabel('Precio unitario (NIO)').fill('99.50')
  await page.getByLabel('Categoría', { exact: true }).selectOption(String(categoryId))
  await page.getByLabel('Talla', { exact: true }).selectOption(String(sizeId))
  await page.getByRole('button', { name: 'Guardar producto' }).click()
  await expect(page.getByText(/Producto #\d+ guardado correctamente/)).toBeVisible()
  await page.goto('/suppliers')
  await page.getByLabel('Empresa', { exact: true }).fill('Setup supplier')
  await page.getByLabel('Nombres del contacto').fill('Setup')
  await page.getByLabel('Apellidos del contacto').fill('Synthetic')
  await page.getByLabel('Teléfono', { exact: true }).fill('0012345678')
  await page.getByLabel('Dirección existente').selectOption(String(addressId))
  await page.getByRole('button', { name: 'Guardar proveedor' }).click()
  await expect(page.getByText(/Proveedor #\d+ guardado correctamente/)).toBeVisible()
  await page.goto('/settings?section=supplier-products')
  const productOption = page.getByLabel('Producto', { exact: true }).getByRole('option').filter({ hasText: 'Setup product' })
  await expect(productOption).toHaveCount(1)
  const productId = await productOption.getAttribute('value')
  await page.getByLabel('Producto', { exact: true }).selectOption(productId!)
  await page.getByLabel('Costo de compra (NIO)').fill('55.25')
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  await expect(page.getByText(/Registro #\d+ guardado correctamente/)).toBeVisible()
  await page.goto('/settings?section=supplier-offerings')
  const supplierOption = page.getByLabel('Proveedor', { exact: true }).getByRole('option').filter({ hasText: 'Setup supplier' })
  await expect(supplierOption).toHaveCount(1)
  const supplierId = await supplierOption.getAttribute('value')
  await page.getByLabel('Proveedor', { exact: true }).selectOption(supplierId!)
  const costOption = page.getByLabel('Producto y costo de compra').getByRole('option').filter({ hasText: 'Setup product' })
  await expect(costOption).toHaveCount(1)
  await page.getByLabel('Producto y costo de compra').selectOption((await costOption.getAttribute('value'))!)
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  await expect(page.getByText(/Registro #\d+ guardado correctamente/)).toBeVisible()
  await page.goto('/customers')
  await page.getByLabel('Nombres', { exact: true }).fill('Setup customer')
  await page.getByLabel('Apellidos', { exact: true }).fill('Synthetic')
  await page.getByLabel('Teléfono', { exact: true }).fill('0012345678')
  await page.getByLabel('Tipo de cliente').selectOption(String(typeId))
  await page.getByLabel('Dirección existente').selectOption(String(addressId))
  await page.getByRole('button', { name: 'Guardar cliente' }).click()
  await expect(page.getByText(/Cliente #\d+ guardado correctamente/)).toBeVisible()
  await page.goto('/purchases')
  await page.getByLabel('Proveedor', { exact: true }).selectOption(supplierId!)
  await page.getByLabel('Empleado responsable').selectOption({ index: 1 })
  await page.getByLabel('Producto ofrecido por el proveedor').selectOption({ index: 1 })
  await page.getByLabel('Cantidad', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Agregar línea' }).click()
  await page.getByRole('button', { name: 'Registrar compra' }).click()
  await expect(page.getByText(/Compra #\d+ registrada correctamente/)).toBeVisible()
  await page.getByLabel('Empleado para recepción').selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Confirmar recepción completa' }).click()
  await expect(page.getByText(/Compra #\d+ recibida correctamente/)).toBeVisible()
  // Close any seeded test shift through the supervised UI before the new cashier operates.
  await page.goto('/cash-register')
  const shifts = await (await page.request.get('/api/v1/cash/shifts')).json()
  const shift = shifts.find((row: { status: string }) => row.status === 'open')
  if (shift) {
    await page.getByLabel('Efectivo final contado (NIO)').fill(shift.expected_amount)
    await page.getByRole('button', { name: 'Confirmar operación de caja' }).click()
    await expect(page.getByLabel('Efectivo inicial contado (NIO)')).toBeVisible()
  }
  await page.getByRole('button', { name: 'Cerrar sesión' }).click()
  await signIn(page, 'setup-cashier', 'Synthetic-password-28!')
  await page.goto('/cash-register')
  await page.getByLabel('Efectivo inicial contado (NIO)').fill('100.00')
  await page.getByRole('button', { name: 'Confirmar operación de caja' }).click()
  await expect(page.getByRole('heading', { name: /Operar turno #/ })).toBeVisible()
  await page.goto('/sales')
  const customerOption = page.getByLabel('Cliente', { exact: true }).getByRole('option').filter({ hasText: 'Setup customer Synthetic' })
  await expect(customerOption).toHaveCount(1)
  await page.getByLabel('Cliente', { exact: true }).selectOption((await customerOption.getAttribute('value'))!)
  await page.getByLabel('Producto', { exact: true }).selectOption(productId!)
  await page.getByRole('button', { name: 'Agregar línea' }).click()
  await page.getByLabel('Efectivo recibido (NIO)').fill('100.00')
  await page.getByRole('button', { name: 'Confirmar venta', exact: true }).click()
  await expect(page.getByText(/Venta #\d+ registrada correctamente. Total: C\$99.50/)).toBeVisible()
  expect((await (await page.request.get(`/api/v1/products/${productId}`)).json()).legacy_stock).toBe(1)
  await page.screenshot({ path: testInfo.outputPath('setup-first-sale.png'), fullPage: true })
  await page.goto('/settings')
  await expect(page.getByText('No tienes permiso para acceder a configuración inicial.')).toBeVisible()
})
