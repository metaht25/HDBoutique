test('real sale is atomic, immutable and reflected in inventory and reports', async ({ page }, testInfo) => {
  await signIn(page, 'Cashier')
  await page.goto('/sales')
  await page.getByRole('combobox', { name: 'Cliente', exact: true }).selectOption({ index: 1 })
  await page.getByRole('textbox', { name: 'ID de empleado existente' }).fill('1')
  await page.getByRole('combobox', { name: 'Producto', exact: true }).selectOption('1')
  await page.getByRole('textbox', { name: 'Cantidad', exact: true }).fill('2')
  await page.getByRole('button', { name: 'Agregar línea' }).click()
  const sent = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/v1/sales')
  await page.getByRole('button', { name: 'Confirmar venta' }).dblclick()
  const request = await sent
  expect(request.postDataJSON()).toMatchObject({ items: [{ product_id: 1, quantity: 2 }] })
  expect(request.postDataJSON()).not.toHaveProperty('total')
  expect(request.headers()['idempotency-key']).toBeTruthy()
  await expect(page.getByText(/Venta #\d+ registrada correctamente. Total: C\$399.00/)).toBeVisible()
  const product = await page.request.get('/api/v1/products/1')
  expect((await product.json()).legacy_stock).toBe(10)
  await page.screenshot({ path: testInfo.outputPath('sales.png'), fullPage: true })
  await page.goto('/reports?type=sales')
  await expect(page.getByText('C$399.00', { exact: true }).first()).toBeVisible()
  await page.reload()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  const csrf = await page.request.get('/api/v1/auth/csrf')
  const denied = await page.request.patch('/api/v1/sales/1', { headers: { Origin: origin, 'X-CSRF-Token': (await csrf.json()).csrf_token }, data: {} })
  expect(denied.status()).toBe(405)
})

test('real purchase receipt increases stock once and preserves cost history', async ({ page }, testInfo) => {
  await signIn(page, 'Manager')
  await page.goto('/purchases')
  await page.getByRole('combobox', { name: 'Proveedor', exact: true }).selectOption('1')
  await page.getByRole('combobox', { name: 'Producto ofrecido por el proveedor' }).selectOption('1')
  await page.getByRole('textbox', { name: 'Cantidad', exact: true }).fill('3')
  await page.getByRole('button', { name: 'Agregar línea' }).click()
  await page.getByRole('textbox', { name: 'Costo de envío (NIO)' }).fill('50.00')
  await page.getByRole('button', { name: 'Registrar compra' }).click()
  await expect(page.getByText(/Compra #\d+ registrada correctamente. Total: C\$411.50/)).toBeVisible()
  expect((await (await page.request.get('/api/v1/products/1')).json()).legacy_stock).toBe(10)
  await page.getByRole('button', { name: 'Confirmar recepción completa' }).dblclick()
  await expect(page.getByText('Compra #1 recibida correctamente.')).toBeVisible()
  expect((await (await page.request.get('/api/v1/products/1')).json()).legacy_stock).toBe(13)
  await page.screenshot({ path: testInfo.outputPath('purchases.png'), fullPage: true })
  const csrf = (await (await page.request.get('/api/v1/auth/csrf')).json()).csrf_token
  const again = await page.request.post('/api/v1/purchases/1/receive', { headers: { Origin: origin, 'X-CSRF-Token': csrf }, data: {} })
  expect(again.status()).toBe(200)
  expect((await (await page.request.get('/api/v1/products/1')).json()).legacy_stock).toBe(13)
  await page.goto('/reports?type=purchases')
  await expect(page.getByRole('cell', { name: 'C$361.50', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Recibida', exact: true })).toBeVisible()
})

test('changing identity in another tab clears the old role and protected data', async ({ page, context }) => {
  await signIn(page, 'Manager')
  await page.goto('/purchases')
  await expect(page.getByRole('button', { name: 'Registrar compra' })).toBeVisible()
  const other = await context.newPage()
  await other.goto('/products')
  await other.getByRole('button', { name: 'Cerrar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Inicia sesión para continuar' })).toBeVisible()
  await signIn(other, 'Cashier')
  await expect(page.getByRole('alert')).toHaveText('No tienes permiso para consultar compras.')
  await expect(page.locator('main table')).toHaveCount(0)
  await expect(page.getByText('purchasing-cashier · Caja')).toBeVisible()
  await other.close()
})
