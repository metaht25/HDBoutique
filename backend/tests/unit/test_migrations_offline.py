"""Offline migration review must not require a database or expose credentials."""

from io import StringIO
from pathlib import Path

from alembic import command
from alembic.config import Config

BACKEND_ROOT = Path(__file__).resolve().parents[2]


def test_offline_sql_has_no_connection_credentials() -> None:
    output = StringIO()
    config = Config(str(BACKEND_ROOT / "alembic.ini"), output_buffer=output)
    command.upgrade(config, "head", sql=True)
    sql = output.getvalue()
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "CREATE TABLE sale_items" in sql
    assert "NUMERIC(12, 2)" in sql
    assert "isolated-test-app-password" not in sql
    assert "postgresql://" not in sql
